-- 1. CONNECTION LOGS (utilisée par backend/src/auth/auth.service.ts)
CREATE TABLE IF NOT EXISTS public.connection_logs (
    id          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id     UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    email       TEXT,
    device      TEXT,
    ip_address  TEXT,
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 2. CUSTOMER ADDRESSES (utilisée par lollyshop)
CREATE TABLE IF NOT EXISTS public.customer_addresses (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    profile_id  UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    address     TEXT NOT NULL,
    city        TEXT,
    postal_code TEXT,
    country     TEXT DEFAULT 'Sénégal',
    is_default  BOOLEAN DEFAULT FALSE,
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 3. SUPPLIERS (utilisée par luxya-pos/purchase-orders)
CREATE TABLE IF NOT EXISTS public.suppliers (
    id             BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name           TEXT NOT NULL,
    contact_person TEXT,
    phone          TEXT,
    email          TEXT,
    address        TEXT,
    shop_id        BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
    created_at     TIMESTAMPTZ DEFAULT NOW(),
    updated_at     TIMESTAMPTZ DEFAULT NOW()
);

DROP TRIGGER IF EXISTS update_suppliers_updated_at ON public.suppliers;
CREATE TRIGGER update_suppliers_updated_at
    BEFORE UPDATE ON public.suppliers
    FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

-- 4. PURCHASE ORDERS (utilisée par luxya-pos/purchase-orders)
CREATE TABLE IF NOT EXISTS public.purchase_orders (
    id          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    supplier_id BIGINT REFERENCES public.suppliers(id) ON DELETE SET NULL,
    shop_id     BIGINT REFERENCES public.shops(id) ON DELETE CASCADE,
    status      TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'ordered', 'received', 'cancelled')),
    notes       TEXT,
    received_at TIMESTAMPTZ,
    created_by  UUID REFERENCES public.profiles(id),
    created_at  TIMESTAMPTZ DEFAULT NOW()
);

-- 5. PURCHASE ORDER ITEMS
CREATE TABLE IF NOT EXISTS public.purchase_order_items (
    id                BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    purchase_order_id BIGINT NOT NULL REFERENCES public.purchase_orders(id) ON DELETE CASCADE,
    product_id        BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    quantity          INTEGER NOT NULL CHECK (quantity > 0),
    cost_price        NUMERIC NOT NULL CHECK (cost_price >= 0),
    received_quantity INTEGER DEFAULT 0,
    created_at        TIMESTAMPTZ DEFAULT NOW()
);

-- 6. PRODUCT VIEWS (utilisée par backend/src/products/products.service.ts)
CREATE TABLE IF NOT EXISTS public.product_views (
    id         BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    shop_id    BIGINT REFERENCES public.shops(id),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

