-- connection_logs: admins only
DROP POLICY IF EXISTS "Admins only: Connection Logs" ON public.connection_logs;
CREATE POLICY "Admins only: Connection Logs" ON public.connection_logs
    FOR ALL TO authenticated
    USING (public.check_is_admin());

-- customer_addresses: utilisateur voit ses propres adresses
DROP POLICY IF EXISTS "Personal: Customer Addresses" ON public.customer_addresses;
CREATE POLICY "Personal: Customer Addresses" ON public.customer_addresses
    FOR ALL TO authenticated
    USING (auth.uid() = profile_id)
    WITH CHECK (auth.uid() = profile_id);

-- suppliers: isolation par boutique
DROP POLICY IF EXISTS "Universal Shop Isolation: Suppliers" ON public.suppliers;
CREATE POLICY "Universal Shop Isolation: Suppliers" ON public.suppliers
    FOR ALL TO authenticated
    USING (public.check_is_admin() OR shop_id = ANY(public.get_user_authorized_shops()))
    WITH CHECK (public.check_is_admin() OR shop_id = ANY(public.get_user_authorized_shops()));

-- purchase_orders: isolation par boutique
DROP POLICY IF EXISTS "Universal Shop Isolation: Purchase Orders" ON public.purchase_orders;
CREATE POLICY "Universal Shop Isolation: Purchase Orders" ON public.purchase_orders
    FOR ALL TO authenticated
    USING (public.check_is_admin() OR shop_id = ANY(public.get_user_authorized_shops()))
    WITH CHECK (public.check_is_admin() OR shop_id = ANY(public.get_user_authorized_shops()));

-- purchase_order_items: via purchase_order
DROP POLICY IF EXISTS "Universal Shop Isolation: Purchase Order Items" ON public.purchase_order_items;
CREATE POLICY "Universal Shop Isolation: Purchase Order Items" ON public.purchase_order_items
    FOR ALL TO authenticated
    USING (
        public.check_is_admin() OR EXISTS (
            SELECT 1 FROM public.purchase_orders po
            WHERE po.id = purchase_order_id
            AND po.shop_id = ANY(public.get_user_authorized_shops())
        )
    );

-- product_views: lecture publique, écriture authentifiée
DROP POLICY IF EXISTS "Public read: Product Views" ON public.product_views;
CREATE POLICY "Public read: Product Views" ON public.product_views
    FOR SELECT TO public USING (true);

DROP POLICY IF EXISTS "Authenticated insert: Product Views" ON public.product_views;
CREATE POLICY "Authenticated insert: Product Views" ON public.product_views
    FOR INSERT TO public WITH CHECK (true);

