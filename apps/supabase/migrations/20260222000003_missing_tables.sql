-- STORAGE BUCKET: PRODUCTS
-- ============================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('products', 'products', TRUE)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "Enable public read access for product images" ON storage.objects;
CREATE POLICY "Enable public read access for product images" ON storage.objects
    FOR SELECT TO public
    USING (bucket_id = 'products');

DROP POLICY IF EXISTS "Enable authenticated insert for product images" ON storage.objects;
CREATE POLICY "Enable authenticated insert for product images" ON storage.objects
    FOR INSERT TO authenticated
    WITH CHECK (bucket_id = 'products' AND (SELECT public.check_is_admin()));

DROP POLICY IF EXISTS "Enable authenticated delete for product images" ON storage.objects;
CREATE POLICY "Enable authenticated delete for product images" ON storage.objects
    FOR DELETE TO authenticated
    USING (bucket_id = 'products' AND (SELECT public.check_is_admin()));

