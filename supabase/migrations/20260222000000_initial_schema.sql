-- B. AUTOMATED STOCK MANAGEMENT
CREATE OR REPLACE FUNCTION public.proc_decrement_stock(p_id BIGINT, p_qty INT, p_variant_id TEXT DEFAULT NULL)
RETURNS VOID AS $$
BEGIN
    UPDATE public.products SET stock = COALESCE(stock, 0) - p_qty WHERE id = p_id AND type != 'service';
    IF p_variant_id IS NOT NULL THEN
        UPDATE public.products SET variants = (
            SELECT jsonb_agg(CASE WHEN (v->>'id')::text = p_variant_id THEN jsonb_set(v, '{stock}', (COALESCE((v->>'stock')::int, 0) - p_qty)::text::jsonb) ELSE v END)
            FROM jsonb_array_elements(variants) v
        ) WHERE id = p_id;
    END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.proc_increment_stock(p_id BIGINT, p_qty INT, p_variant_id TEXT DEFAULT NULL)
RETURNS VOID AS $$
BEGIN
    UPDATE public.products SET stock = COALESCE(stock, 0) + p_qty WHERE id = p_id AND type != 'service';
    IF p_variant_id IS NOT NULL THEN
        UPDATE public.products SET variants = (
            SELECT jsonb_agg(CASE WHEN (v->>'id')::text = p_variant_id THEN jsonb_set(v, '{stock}', (COALESCE((v->>'stock')::int, 0) + p_qty)::text::jsonb) ELSE v END)
            FROM jsonb_array_elements(variants) v
        ) WHERE id = p_id;
    END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.handle_sale_item_stock_change()
RETURNS TRIGGER AS $$
DECLARE v_sale_type TEXT; v_sale_status TEXT;
BEGIN
    SELECT type, status INTO v_sale_type, v_sale_status FROM public.sales WHERE id = COALESCE(NEW.sale_id, OLD.sale_id);
    IF v_sale_type = 'quote' OR v_sale_status = 'cancelled' THEN RETURN COALESCE(NEW, OLD); END IF;
    IF (TG_OP = 'INSERT') THEN
        IF NEW.product_id IS NOT NULL THEN
            PERFORM public.proc_decrement_stock(NEW.product_id, NEW.quantity, NEW.variant_id);
            UPDATE public.products SET sales_count = COALESCE(sales_count, 0) + NEW.quantity WHERE id = NEW.product_id;
        END IF;
    ELSIF (TG_OP = 'DELETE') THEN
        IF OLD.product_id IS NOT NULL THEN
            PERFORM public.proc_increment_stock(OLD.product_id, OLD.quantity, OLD.variant_id);
            UPDATE public.products SET sales_count = GREATEST(0, COALESCE(sales_count, 0) - OLD.quantity) WHERE id = OLD.product_id;
        END IF;
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sale_items_stock ON public.sale_items;
CREATE TRIGGER trg_sale_items_stock AFTER INSERT OR DELETE ON public.sale_items FOR EACH ROW EXECUTE FUNCTION public.handle_sale_item_stock_change();

-- C. LOYALTY POINTS AUTOMATION
CREATE OR REPLACE FUNCTION public.credit_loyalty_points()
RETURNS TRIGGER AS $$
DECLARE points_to_add INTEGER;
BEGIN
    IF (NEW.customer_id IS NOT NULL AND NEW.status = 'completed' AND (OLD.status IS NULL OR OLD.status != 'completed')) THEN
        points_to_add := FLOOR(NEW.total_amount / 100);
        IF points_to_add > 0 THEN
            UPDATE public.profiles SET loyalty_points = COALESCE(loyalty_points, 0) + points_to_add WHERE id = NEW.customer_id;
            INSERT INTO public.loyalty_history (profile_id, points_change, reason, sale_id)
            VALUES (NEW.customer_id, points_to_add, 'Achat boutique / Commande #' || NEW.id, NEW.id);
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_sale_completed_loyalty ON public.sales;
CREATE TRIGGER on_sale_completed_loyalty AFTER UPDATE ON public.sales FOR EACH ROW EXECUTE FUNCTION public.credit_loyalty_points();

-- D. SECURITY HELPERS
CREATE OR REPLACE FUNCTION public.check_is_admin() RETURNS BOOLEAN AS $$
    SELECT COALESCE(role = 'admin' OR is_super_admin, false) FROM public.profiles WHERE id = auth.uid();
$$ LANGUAGE sql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.get_user_authorized_shops() RETURNS BIGINT[] AS $$
    SELECT COALESCE(shop_ids, ARRAY[shop_id]) FROM public.profiles WHERE id = auth.uid();
$$ LANGUAGE sql SECURITY DEFINER;
